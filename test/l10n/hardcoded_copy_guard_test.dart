import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

import 'support/copy_inventory.dart';

/// ADR-025 §6 G-HC + G-A11Y (L-INF, test S-8): no new hard-coded
/// user-facing text — in Dart copy, accessibility text (labels, hints,
/// tooltips, announcements) or Android's native strings — beyond the
/// documented, non-growing baseline in `hardcoded_copy_baseline.tsv`.
///
/// The baseline is the legacy text that existed before L-INF; each entry is
/// an approved exception only until its extraction batch moves it into the
/// ARB catalogue. Any addition fails — including an edit to an existing
/// string, which is a new string. An entry whose text is gone also fails
/// until it is removed from the baseline: it only ever shrinks.
///
/// Regenerate only on an authorized extraction batch:
/// `flutter test test/l10n/hardcoded_copy_guard_test.dart
///  --dart-define=WRITE_COPY_BASELINE=true`, then review the diff.
const _baseline = 'test/l10n/hardcoded_copy_baseline.tsv';
const _write = bool.fromEnvironment('WRITE_COPY_BASELINE');

const _header = '''
# THIRTY hard-coded user-facing text baseline (ADR-025 §6 G-HC / G-A11Y).
# Generated by test/l10n/hardcoded_copy_guard_test.dart; review every diff.
# Columns: kind (copy | a11y | android) <TAB> file <TAB> count <TAB> text.
# Approved exception, for every entry below: legacy English text present
# before L-INF (b62984bc), shown exactly as today; it moves into the ARB
# catalogue in its extraction batch and its entry is then removed. Nothing
# may be added here except by an authorized batch that also explains it.
''';

void main() {
  final current = counts(inventory());

  test('S-8: no hard-coded user-facing text beyond the baseline', () {
    if (_write) {
      final lines = [
        for (final MapEntry(:key, :value) in current.entries)
          switch (key.split('\t')) {
            [final kind, final file, ...final rest] =>
              '$kind\t$file\t$value\t${escapeField(rest.join('\t'))}',
            _ => throw StateError(key),
          },
      ]..sort();
      File(_baseline).writeAsStringSync('$_header${lines.join('\n')}\n');
    }
    final diff = compareToBaseline(current, readBaseline(_baseline));
    expect(
      diff.added,
      isEmpty,
      reason:
          'New hard-coded user-facing text. Put it in lib/l10n/arb/'
          'app_en.arb and read it through AppLocalizations instead.',
    );
    expect(
      diff.stale,
      isEmpty,
      reason: 'The baseline only shrinks: remove the entries listed.',
    );
  });

  test(
    'S-8: the baseline covers Dart copy, accessibility text and Android',
    () {
      final kinds = {for (final k in current.keys) k.split('\t').first};
      expect(kinds, containsAll(['copy', 'a11y', 'android']));
      expect(
        current.keys.where((k) => k.contains('lib/l10n/gen/')),
        isEmpty,
        reason: 'generated code is never counted as hand-written copy',
      );
    },
  );

  group('S-8: the guard fails on new text', () {
    late Directory dir;
    setUp(() => dir = Directory.systemTemp.createTempSync('thirty_copy_'));
    tearDown(() => dir.deleteSync(recursive: true));

    test('new copy, a new accessibility label and a new native channel '
        'name are each reported', () {
      final dart = File('${dir.path}/new_widget.dart')
        ..writeAsStringSync('''
Widget build() => Column(children: [
  Text('Some brand new words'),
  Semantics(label: 'A new spoken label', child: Icon(icons.x)),
  Tooltip(message: 'Another new hint'),
]);
void f() { throw StateError('Diagnostic text is technical'); }
''');
      final kotlin = Directory('${dir.path}/main/kotlin')
        ..createSync(recursive: true);
      File('${kotlin.path}/X.kt').writeAsStringSync(
        '    private const val CHANNEL_NAME = "A new channel"\n',
      );
      final found = counts([
        ...dartCandidates([dart.path]),
        ...androidCandidates('${dir.path}/main'),
      ]);
      final diff = compareToBaseline(found, const {});
      final added = diff.added.join('\n');
      expect(added, contains('copy\t'));
      expect(added, contains('Some brand new words'));
      expect(added, contains('a11y\t'));
      expect(added, contains('A new spoken label'));
      expect(added, contains('Another new hint'));
      expect(added, contains('android\t'));
      expect(added, contains('A new channel'));
      expect(added, isNot(contains('Diagnostic text')));
    });

    test('an edited existing string is an addition, and its old entry is '
        'stale', () {
      final diff = compareToBaseline(
        {'copy\tlib/x.dart\tHello there, friend': 1},
        {'copy\tlib/x.dart\tHello there': 1},
      );
      expect(diff.added, hasLength(1));
      expect(diff.stale, hasLength(1));
    });

    test('a second copy of a baselined string is an addition', () {
      final diff = compareToBaseline(
        {'copy\tlib/x.dart\tHello there': 2},
        {'copy\tlib/x.dart\tHello there': 1},
      );
      expect(diff.added.single, contains('×1'));
    });
  });
}
